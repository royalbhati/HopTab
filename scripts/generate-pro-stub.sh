    public struct Session {
        public let eventTitle: String
        public var phase: Phase
        public var phaseEndsAt: Date
        public var completedWorkIntervals: Int
    }

    public private(set) var current: Session?
    public var isActive: Bool { current != nil }
    /// (eventTitle, minutes, intervalNumber)
    public var onWorkStarted: ((String, Int, Int) -> Void)?
    /// (eventTitle, total focused seconds this session)
    public var onSessionEnded: ((String, TimeInterval) -> Void)?

    public init() {}
    public func start(eventTitle: String, eventEndDate: Date?) {}
    public func stop() {}
    public func skipBreak() {}
