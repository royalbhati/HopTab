// MARK: - Stub banner

/// Logged once when the stub module is instantiated, so it is obvious in
/// Console.app / `log stream` that this build has no Pro implementation.
private func logStubBannerOnce() {
    struct Once { @MainActor static var done = false }
    MainActor.assumeIsolated {
        guard !Once.done else { return }
        Once.done = true
        NSLog("[HopTabPro] OPEN-SOURCE STUB — Pro features are unavailable in this build.")
    }
}

