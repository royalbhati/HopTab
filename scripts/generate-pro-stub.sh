#!/bin/bash
#
# generate-pro-stub.sh — create a compile-only stub for the closed-source
# HopTabPro Swift package.
#
# HopTab.xcodeproj references a *local* Swift package at ./HopTabPro. The real
# implementation lives in a separate private repo and is gitignored, so a fresh
# clone (and every CI run) fails with:
#
#     The folder "HopTabPro" doesn't exist.
#
# This script writes a minimal, API-compatible stub package at ./HopTabPro so
# the open-source tree builds a working FREE-TIER app with Pro disabled.
#
# SAFETY: if ./HopTabPro already exists — i.e. you are the maintainer with the
# real private package checked out — this script does NOTHING and exits 0. It
# will never overwrite a real implementation.
#
# Usage:  bash scripts/generate-pro-stub.sh
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PKG_DIR="$REPO_ROOT/HopTabPro"

if [ -d "$PKG_DIR" ]; then
  echo "==> HopTabPro/ already exists — leaving it untouched (real package or previously generated stub)."
  exit 0
fi

echo ""
echo "┌──────────────────────────────────────────────────────────────────────┐"
echo "│  HopTabPro: OPEN-SOURCE STUB                                         │"
echo "│                                                                      │"
echo "│  The real HopTabPro package is closed source and is not part of this  │"
echo "│  repository. Generating a compile-only stub so the app builds.        │"
echo "│                                                                      │"
echo "│  PRO FEATURES ARE UNAVAILABLE IN THIS BUILD:                          │"
echo "│    time tracking · calendar auto-switch · scheduling · focus modes    │"
echo "│    display auto-profiles · unlimited rules/profiles · window undo     │"
echo "│    auto-declutter · screen breaks · focus sessions · pomodoro         │"
echo "│                                                                      │"
echo "│  Everything in the free tier works normally.                          │"
echo "│  Pro: https://buy.polar.sh/polar_cl_iKgZQ7w4AWRhnNzsnQBl80syKnFJGHJj1Pv6d2a9tD7"
echo "└──────────────────────────────────────────────────────────────────────┘"
echo ""

mkdir -p "$PKG_DIR/Sources/HopTabPro"

# ---------------------------------------------------------------------------
# Package.swift — shape, product name and target name must match the real one.
# ---------------------------------------------------------------------------
cat > "$PKG_DIR/Package.swift" <<'PACKAGE_EOF'
// swift-tools-version: 5.9
//
// OPEN-SOURCE STUB of the closed-source HopTabPro package.
// Generated by scripts/generate-pro-stub.sh — do not commit.
//
import PackageDescription

let package = Package(
    name: "HopTabPro",
    platforms: [.macOS(.v14)],
    products: [
        .library(name: "HopTabPro", targets: ["HopTabPro"]),
    ],
    targets: [
        .target(name: "HopTabPro"),
    ]
)
PACKAGE_EOF

# ---------------------------------------------------------------------------
# Stub sources. Every symbol here is one the free target reaches for through
# HopTab/Pro/ProBridge.swift or HopTab/App/AppDelegate.swift. Signatures match
# the real module; every body is a no-op / false / nil / 0.
# ---------------------------------------------------------------------------
cat > "$PKG_DIR/Sources/HopTabPro/HopTabProStub.swift" <<'STUB_EOF'
//
//  HopTabProStub.swift
//
//  OPEN-SOURCE STUB of the closed-source HopTabPro module.
//  Generated by scripts/generate-pro-stub.sh — do not commit, do not edit.
//
//  This file exists so the open-source HopTab tree compiles and runs as a
//  fully functional FREE-TIER app. Every Pro entry point below is inert:
//  `isLicensed` is always false, services never start, and each Pro settings
//  section renders a short "not available in this build" notice.
//

import AppKit
